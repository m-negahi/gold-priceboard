<h3>این صفحه برای چیست؟</h3>
<p>میزکار وضعیت لحظه‌ای موتور قیمت را در یک نگاه نشان می‌دهد: قیمت نهایی هر ابزار، این‌که کدام منبع آن را داده، کدام منبع خطا می‌دهد و کدام بازارها الان بازند. هر ۵ ثانیه از سرور تازه می‌شود؛ وقتی برگه پنهان باشد متوقف می‌ماند.</p>

<h3>نوار آمار</h3>
<dl>
    <dt>ابزار فعال</dt><dd>تعداد ابزارهایی که قیمت‌گیری برایشان روشن است، و چند تای آن‌ها هم‌اکنون قیمت دارند.</dd>
    <dt>کهنه</dt><dd>ابزارهایی که بازارشان باز است ولی از پنجرهٔ تازگی (تنظیم <span class="ltr">stale_after_seconds</span>) عبور کرده‌اند. بازار بسته کهنه حساب نمی‌شود.</dd>
    <dt>منابع سالم</dt><dd>منبع‌هایی که آخرین دریافتشان موفق بوده، از کل منبع‌ها.</dd>
    <dt>وقفهٔ خطا</dt><dd>منبع‌هایی که پس از چند خطای پیاپی موقتاً از چرخه خارج شده‌اند (قطع‌کنندهٔ مدار). شمارش معکوس بازگشت در «خطاها» دیده می‌شود.</dd>
    <dt>آخرین دریافت</dt><dd>زمان آخرین پاسخ موفق از هر منبعی. اگر از چند دقیقه گذشت، زمان‌بند یا Horizon را بررسی کنید.</dd>
    <dt>بازارها</dt><dd>چند بازار از بازارهای تعریف‌شده (تنظیم <span class="ltr">market_hours</span>) الان بازند.</dd>
    <dt>روند امروز</dt><dd>تعداد ابزارهای رشدی و نزولی نسبت به قیمت پایانی قبلی.</dd>
</dl>

<h3>قیمت‌های لحظه‌ای</h3>
<p>ردیف هر ابزار: قیمت میانگین (و خرید/فروش در صفحه‌های عریض)، تغییر نسبت به پایانی قبلی، منبعی که این قیمت را داده و زمان آن. ستون «۲۴ ساعت» یک نمودار کوچک از تاریخچهٔ InfluxDB است و فقط وقتی سرویس تاریخچه در دسترس باشد نشان داده می‌شود. نشان «کهنه» یعنی بازار باز است و خوراک نمی‌رسد؛ «بازار بسته» یک حالت عادی است و قیمت پایانی را نشان می‌دهد.</p>

<h3>بیشترین حرکت‌ها</h3>
<p>پنج رشد و پنج افت بزرگ امروز بر اساس درصد تغییر. ردیف کهنه با نشان زمان‌سنج مشخص می‌شود تا یک جهش ساختگی ناشی از خوراک قطع‌شده با حرکت واقعی اشتباه نشود.</p>

<h3>مقایسهٔ منابع</h3>
<p>برای هر ابزار، آخرین قیمتی که هر منبع تحویل داده در کنار قیمت نهایی می‌نشیند. انحراف این‌طور حساب می‌شود:</p>
<p class="ltr num">(mid<sub>source</sub> − mid<sub>final</sub>) × 100 ÷ mid<sub>final</sub></p>
<p>نتیجه علامت‌دار است: مثبت یعنی آن منبع گران‌تر از قیمت نهایی می‌گوید. انحراف بیشتر از آستانه (پیش‌فرض ۰٫۵٪، تنظیم <span class="ltr">provider_deviation_alert_percent</span>) قرمز می‌شود. سلولی که تیک دارد منبعی است که هم‌اکنون قیمت نهایی را می‌دهد؛ عدد کنار هر سلول سن آن قیمت است. سلول خالی یعنی آن منبع در حافظه قیمتی برای این ابزار ندارد — یا هنوز دریافت نشده، یا از پنجرهٔ تازگی گذشته و پاک شده است.</p>

<h3>بازارها</h3>
<p>برای هر بازار نوار ۲۴ ساعتهٔ امروز (به وقت تهران): بخش روشن ساعت‌های معامله است و خط عمودی «اکنون». زیر آن نوشته می‌شود بازار کی بسته یا باز می‌شود. بازاری که تقویم ندارد همیشه باز حساب می‌شود.</p>

<h3>خطاها</h3>
<p>منبع‌هایی که همین حالا مشکل دارند: تعداد خطای پیاپی، آخرین دریافت موفق، شمارش معکوس بازگشت از وقفه و متن کوتاه‌شدهٔ آخرین خطا (هرگز پاسخ کامل یا کلید).</p>

<h3>نیاز به توجه</h3>
<p>یک خط برای هر مشکل، به ترتیب شدت: منبع در وقفه، منبع در حال خطا، قیمت کهنه، ابزار بدون قیمت.</p>

<h3>اقدام سریع</h3>
<p>«اجرای یک دور دریافت» همان کاری را می‌کند که زمان‌بند هر ثانیه می‌کند، با این تفاوت که منتظر نوبت بعدی هر منبع نمی‌ماند: هر منبع فعال که در وقفهٔ خطا نیست همین حالا یک بار دریافت می‌شود. نتیجه به شکل اعلان می‌آید و چند ثانیه بعد قیمت‌ها تازه می‌شوند.</p>

<h3>نقشهٔ بخش‌ها</h3>
<ul>
    <li><strong>بالا:</strong> نوار آمار و جدول قیمت — وضعیت موتور قیمت.</li>
    <li><strong>میانه:</strong> حرکت‌ها و مقایسهٔ منابع — کیفیت داده.</li>
    <li><strong>پایین:</strong> بازارها، خطاها، نیاز به توجه، اقدام سریع — عملیات.</li>
    <li><strong>بخش مالی</strong> (کیف پول‌ها، فاکتورهای امروز، اشتراک‌های رو به انقضا، درآمد امروز) با ماژول Billing اضافه می‌شود و زیر جدول قیمت، پیش از حرکت‌ها می‌نشیند. تا آن زمان جای خالی نمایش داده نمی‌شود.</li>
</ul>
